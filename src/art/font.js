function parseGlyph(char, [offset, source]) {
  const rows = source.split('|');
  const width = rows[0].length;
  rows.forEach((row, index) => {
    if (row.length !== width) throw new Error(`Glyph '${char}' row ${index} is ${row.length} wide, expected ${width}`);
  });
  const top = ABOVE + offset;
  if (top < 0 || top + rows.length > LINE_HEIGHT) throw new Error(`Glyph '${char}' doesn't fit the line`);
  const dots = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < width; x++) if (row[x] === '#') dots.push([x, top + y]);
  });
  return { width, dots };
}

export const GLYPHS = Object.fromEntries(
  Object.entries(GLYPH_SOURCES).map(([char, source]) => [char, parseGlyph(char, source)]),
);

function glyphFor(char) {
  const glyph = GLYPHS[char];
  if (!glyph) throw new Error(`The font has no glyph for '${char}'`);
  return glyph;
}

export function textWidth(text) {
  let width = 0;
  for (const char of text) {
    width += (char === ' ' ? SPACE_WIDTH : glyphFor(char).width) + LETTER_SPACING;
  }
  return Math.max(0, width - LETTER_SPACING);
}

// One line of text as a pixel image in a palette colour. A shadow colour
// adds a copy one pixel down and to the right, behind the text, so it reads
// against any background.
export function textImage(text, colourName, shadowName = null) {
  const shadow = shadowName ? 1 : 0;
  const image = createImage(textWidth(text) + shadow, LINE_HEIGHT + shadow);
  const passes = shadowName ? [[shadow, colour(shadowName)], [0, colour(colourName)]] : [[0, colour(colourName)]];
  for (const [offset, value] of passes) {
    let x = 0;
    for (const char of text) {
      if (char === ' ') {
        x += SPACE_WIDTH + LETTER_SPACING;
        continue;
      }
      const glyph = glyphFor(char);
      for (const [dx, dy] of glyph.dots) setPixel(image, x + dx + offset, dy + offset, value);
      x += glyph.width + LETTER_SPACING;
    }
  }
  return image;
}
